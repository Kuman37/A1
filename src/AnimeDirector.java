public class AnimeDirector {

    public void constructCommunityDrivenAction(AnimeBuilder builder) {
        builder.setTitle("Crimson Blade X")
                .setGenre("Shonen Action")
                .setPrimaryColorPalette("Black and Red")
                .setEpisodeDurationMinutes(24)
                .setStudio("Premium Animation Community");
    }

    public void constructGrimdarkFantasy(AnimeBuilder builder) {
        builder.setTitle("Shadows of the balls")
                .setGenre("Dark Fantasy / Horror")
                .setPrimaryColorPalette("Monochrome with Crimson Accents")
                .setEpisodeDurationMinutes(45)
                .setStudio("Elite Art Studio");
    }
}